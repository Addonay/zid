#!/usr/bin/env python3
"""Generate a catalogue from supplied settings and Zed UI metadata. Never edits JSON assets."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'assets/settings/default.json'
text = source.read_text()
# Match strings before comments so URLs and escaped quotes survive.
clean = re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*[\s\S]*?\*/', lambda m: m[0] if m[0].startswith('"') else ' ', text)
clean = re.sub(r',\s*([}\]])', r'\1', clean)
defaults = json.loads(clean)
rust = (ROOT / '.ref/zed/crates/settings_ui/src/page_data.rs').read_text()
pages = ['general', 'appearance', 'keymap', 'editor', 'languages_and_tools', 'search_and_files', 'window_and_layout', 'panels', 'debugger', 'terminal', 'version_control', 'collaboration', 'ai', 'network', 'developer']
metadata = {}
for i, match in enumerate(list(re.finditer(r'^fn (\w+)_page\([^\n]*', rust, re.M))):
    page = match[1]
    if page not in pages:
        continue
    end = re.search(r'^fn \w+\(', rust[match.end():], re.M)
    body = rust[match.end():match.end() + end.start()] if end else rust[match.end():]
    section = 'General'
    events = list(re.finditer(r'SectionHeader\("([^"]+)"\)|title: "((?:\\.|[^"\\])*)"', body))
    for n, event in enumerate(events):
        if event[1]:
            section = event[1]
            continue
        block = body[event.end():events[n + 1].start() if n + 1 < len(events) else len(body)]
        path = re.search(r'json_path: Some\("([^"]+)"\)', block)
        desc = re.search(r'description: (?:Some\()?"((?:\\.|[^"\\])*)"', block)
        if path:
            metadata[path[1]] = (page, section, event[2], desc[1] if desc else '')

def guess(path):
    head = path[0]
    if head in ('project_panel', 'outline_panel', 'collaboration_panel', 'notification_panel'): return 'panels'
    if head in ('terminal', 'debugger'): return head
    if head in ('title_bar', 'status_bar', 'tab_bar', 'tabs') or head.startswith(('window_', 'pane_', 'dock')): return 'window_and_layout'
    if head.startswith(('git', 'git_')): return 'version_control'
    if head in ('agent', 'assistant', 'edit_predictions', 'language_models', 'context_servers'): return 'ai'
    if head in ('languages', 'lsp', 'language_servers', 'formatter', 'file_types'): return 'languages_and_tools'
    if head.startswith(('search', 'file_', 'worktree')): return 'search_and_files'
    if head in ('proxy', 'http_proxy', 'network'): return 'network'
    if 'font' in head or head in ('theme', 'icon_theme', 'ui_density', 'experimental.theme_overrides'): return 'appearance'
    return 'editor'

entries = []
def walk(value, parts):
    path = '.'.join(parts)
    if isinstance(value, dict) and value and parts != ['theme']:
        for k, v in value.items(): walk(v, parts + [k])
        return
    if path == '$schema': return
    page, section, title, desc = metadata.get(path, (guess(parts), parts[0].replace('_', ' ').title() if len(parts) > 1 else 'General', parts[-1].replace('_', ' ').title(), ''))
    entries.append(dict(path=path, segments=parts, page=page, section=section, title=title, description=desc, default=json.dumps(value, ensure_ascii=False, separators=(',', ':'))))
walk(defaults, [])
known = {entry['path'] for entry in entries}
for path, (page, section, title, desc) in metadata.items():
    if path not in known:
        # No explicit value in default.json: retain the unset/inherited state.
        entries.append(dict(path=path, segments=path.split('.'), page=page, section=section, title=title, description=desc, default='null'))
section_order = {}
item_order = {}
for path, (page, section, title, desc) in metadata.items():
    section_order.setdefault((page, section), len(section_order))
    item_order[path] = len(item_order)
entries.sort(key=lambda e: (pages.index(e['page']), section_order.get((e['page'], e['section']), 10000), item_order.get(e['path'], 10000), e['section']))

quote = lambda s: json.dumps(s, ensure_ascii=False)
lines = ['//! Generated by tools/import_settings.py from the reference Zed checkout.', 'pub const defaults = @embedFile("settings/default.json");', 'pub const Entry = struct { path: []const u8, segments: []const []const u8, page: []const u8, section: []const u8, title: []const u8, description: []const u8, default: []const u8 };', 'pub const entries = [_]Entry{']
for e in entries:
    segments = '&.{' + ', '.join(map(quote, e['segments'])) + '}'
    lines.append('    .{ ' + ', '.join('.' + k + ' = ' + (segments if k == 'segments' else quote(v)) for k,v in e.items()) + ' },')
lines += ['};', '']
for asset in sorted((ROOT / 'assets/settings').glob('*.json')):
    if asset.name != 'default.json':
        lines.append(f'pub const {asset.stem} = @embedFile({quote("settings/" + asset.name)});')
lines.append('')
(ROOT / 'assets/settings.zig').write_text('\n'.join(lines))
print(f'Generated {len(entries)} settings entries ({len(known)} explicit defaults, {len(entries) - len(known)} unset/inherited); source JSON untouched')
