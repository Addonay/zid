pub fn fileForPath(path: []const u8) []const u8 {
    const slash = std.mem.lastIndexOfScalar(u8, path, '/') orelse 0;
    const backslash = std.mem.lastIndexOfScalar(u8, path, 92) orelse 0;
    const sep = @max(slash, backslash);
    const base = if (sep > 0) path[sep + 1 ..] else path;
    for (stems) |entry| if (std.mem.eql(u8, base, entry.key)) return svg(entry.icon);
    var best_icon: ?[]const u8 = null;
    var best_len: usize = 0;
    for (suffixes) |entry| {
        if (entry.key.len > base.len or entry.key.len <= best_len) continue;
        if (!std.mem.endsWith(u8, base, entry.key)) continue;
        const start = base.len - entry.key.len;
        const is_compound = std.mem.indexOfScalar(u8, entry.key, '.') != null;
        if (start == 0 or is_compound or base[start - 1] == '.') {
            best_icon = entry.icon;
            best_len = entry.key.len;
        }
    }
    if (best_icon) |icon| return svg(icon);
    return svg("default");
}
